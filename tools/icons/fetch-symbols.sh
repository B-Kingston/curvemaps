#!/bin/sh
# Fetch Material Symbols Rounded (weight 400, grade 0, opsz 24) as Android
# vector drawables.
#
#   tools/icons/fetch-symbols.sh <name> [<name> ...]   fetch, convert, add to the manifest
#   tools/icons/fetch-symbols.sh --all                 refetch every name in the manifest
#
# For each <name> it writes app/src/main/res/drawable/ms_<name>.xml (outlined)
# and ms_<name>_fill.xml (filled) and records <name> in tools/icons/symbols.txt
# (sorted, unique). Use them as
#   Icon(painterResource(R.drawable.ms_<name>), contentDescription = null)
# Source: github.com/google/material-design-icons (Apache-2.0, see
# docs/agents/ui-theme.md and app/licences/libraries/material-symbols.json).
# Fails loudly on a 404, an SVG with more than one path, or any transform.
set -eu

here=$(cd "$(dirname "$0")" && pwd)
repo=$(cd "$here/../.." && pwd)
manifest="$here/symbols.txt"
out="$repo/app/src/main/res/drawable"
base="https://raw.githubusercontent.com/google/material-design-icons/master/symbols/web"

usage() {
    sed -n '2,13p' "$0" | sed 's/^# \{0,1\}//' >&2
    exit 2
}

[ $# -ge 1 ] || usage

if [ "$1" = "--all" ]; then
    [ $# -eq 1 ] || usage
    [ -f "$manifest" ] || { echo "no manifest at $manifest" >&2; exit 1; }
    set -- $(grep -v '^[[:space:]]*$' "$manifest")
fi

tmp=$(mktemp -d "${TMPDIR:-/tmp}/symbols.XXXXXX")
trap 'rm -rf "$tmp"' EXIT

# Convert one SVG (stdin) to a vector drawable (stdout); exits non-zero if it is
# not the single-path 24px symbol shape this script understands.
convert() {
    python3 -I -c '
import re, sys
svg = sys.stdin.read()
name = sys.argv[1]
def fail(why):
    sys.exit("%s: %s" % (name, why))
if not re.search(r"viewBox=\"0 -960 960 960\"", svg):
    fail("unexpected viewBox (want 0 -960 960 960)")
if re.search(r"transform=|<g[\s>]|<use|<circle|<rect|<polygon|<ellipse|<line", svg):
    fail("transform or non-path element; not handled")
paths = re.findall(r"<path\b([^>]*)/?>", svg)
if len(paths) != 1:
    fail("expected exactly one <path>, found %d" % len(paths))
attrs = dict(re.findall(r"([\w:-]+)=\"([^\"]*)\"", paths[0]))
if set(attrs) != {"d"}:
    fail("path has attributes other than d: %s" % sorted(set(attrs) - {"d"}))
print("""<?xml version="1.0" encoding="utf-8"?>
<!-- Material Symbols Rounded (Apache-2.0), generated by tools/icons/fetch-symbols.sh -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="960"
    android:viewportHeight="960">
    <group android:translateY="960">
        <path
            android:fillColor="#FF000000"
            android:pathData="%s" />
    </group>
</vector>""" % attrs["d"])
' "$1"
}

fetch_one() {
    name=$1
    case $name in
        ''|*[!a-z0-9_]*) echo "bad icon name: $name" >&2; return 1 ;;
    esac
    for variant in "" _fill1; do
        file="${name}${variant}_24px.svg"
        url="$base/$name/materialsymbolsrounded/$file"
        curl -fsS "$url" -o "$tmp/$file" || { echo "$name: download failed: $url" >&2; return 1; }
        convert "$name$variant" < "$tmp/$file" > "$tmp/$name$variant.xml" || return 1
    done
    # Both variants converted: only now touch the drawables.
    mv "$tmp/$name.xml" "$out/ms_${name}.xml"
    mv "$tmp/${name}_fill1.xml" "$out/ms_${name}_fill.xml"
}

mkdir -p "$out"
failed=""
done_names=""
for name in "$@"; do
    if fetch_one "$name"; then
        done_names="$done_names $name"
        echo "ok   $name"
    else
        failed="$failed $name"
        echo "FAIL $name" >&2
    fi
done

if [ -n "$done_names" ]; then
    { [ -f "$manifest" ] && cat "$manifest"; for n in $done_names; do echo "$n"; done; } \
        | grep -v '^[[:space:]]*$' | LC_ALL=C sort -u > "$tmp/manifest"
    mv "$tmp/manifest" "$manifest"
fi

if [ -n "$failed" ]; then
    echo "failed:$failed" >&2
    exit 1
fi
